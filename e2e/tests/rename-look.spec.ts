import { test, expect } from '@playwright/test';
import { generate } from '../helpers';
import { register, uniqueName, save, thumbnail, card } from '../library-helpers';

test('Enter and blur renames persist, blank rename is rejected and recoverable', async ({ page }) => {
  await register(page);
  await page.getByRole('link', { name: 'Make your first look', exact: true }).click();
  await generate(page);
  const original = uniqueName('Original'), renamed = uniqueName('Renamed'), recovered = uniqueName('Recovered');
  await save(page, original);
  await page.getByRole('button', { name: 'Open library', exact: true }).click();
  const article = card(page, original);
  await article.getByRole('button', { name: 'Rename', exact: true }).click();
  const editor = article.getByRole('textbox');
  await expect(editor).toHaveValue(original);
  await editor.fill(renamed);
  await editor.press('Enter');
  await thumbnail(page, renamed);
  await expect(card(page, renamed).getByRole('button', { name: renamed, exact: true })).toBeVisible();
  await page.reload();
  await thumbnail(page, renamed);
  await expect(page.getByText(original, { exact: true })).toHaveCount(0);
  await expect(page.getByRole('img', { name: original, exact: true })).toHaveCount(0);
  await card(page, renamed).getByRole('button', { name: 'Rename', exact: true }).click();
  await card(page, renamed).getByRole('textbox').fill('   ');
  await card(page, renamed).getByRole('textbox').press('Enter');
  await expect(page.getByText('Invalid or missing request fields or settings.', { exact: true })).toBeVisible();
  await expect(page.getByRole('article')).toHaveCount(1);
  await thumbnail(page, renamed);
  await page.reload();
  await thumbnail(page, renamed);
  await card(page, renamed).getByRole('button', { name: 'Rename', exact: true }).click();
  await card(page, renamed).getByRole('textbox').fill(recovered);
  await page.getByRole('heading', { name: 'Your looks', exact: true }).click();
  await thumbnail(page, recovered);
  await page.reload();
  await thumbnail(page, recovered);
  await expect(page.getByRole('img', { name: renamed, exact: true })).toHaveCount(0);
});
